"""Календарный график: недели, диапазоны групп и состояния дней."""

import csv
import datetime as dt
import io

from whensclass.parser.calendar import HOLIDAYS, PRACTICE, SESSION, expand, parse, weeks

TODAY = dt.date(2026, 11, 16)


def _sheet(rows):
    out = io.StringIO()
    csv.writer(out).writerows(rows)
    return out.getvalue()


# Раскладка как у настоящего листа: сверху месяцы, номера недель и диапазоны дат,
# дальше курсы и строки групп. Месяц в заголовке — тот, в котором неделя кончается.
SHEET = _sheet([
    ["", "", "", "", "", "", ""],
    ["месяц", "сентябрь", "", "", "", "октябрь", ""],
    ["№ недели", "1", "2", "3", "4", "5", "6"],
    ["дата", "1-6", "7-13", "14-20", "21-27", "28-4", "5-11"],
    ["1 КУРС на базе основного общего образования"],
    ["АА-101/1-2", "", "::", "", "", "=", ""],
    ["ББ-102", "УП", "", "", "ПП", "", "Дфз"],
    ["ВВ-103", "", "", "", "", "", ""],
])


def test_weeks_берут_месяц_конца_недели():
    got = weeks(list(csv.reader(io.StringIO(SHEET))), TODAY)
    assert [(w.number, w.start.isoformat(), w.end.isoformat()) for w in got] == [
        (1, "2026-09-01", "2026-09-06"),
        (2, "2026-09-07", "2026-09-13"),
        (3, "2026-09-14", "2026-09-20"),
        (4, "2026-09-21", "2026-09-27"),
        # «28-4» под «октябрь» — с 28 сентября по 4 октября.
        (5, "2026-09-28", "2026-10-04"),
        (6, "2026-10-05", "2026-10-11"),
    ]


def test_диапазон_групп_раскрывается_только_по_своим():
    known = {"АА-101/1", "АА-101/3", "ББ-102"}
    assert expand("АА-101/1-3", known) == ["АА-101/1", "АА-101/3"]  # /2 в расписании нет
    assert expand("ББ-102", known) == ["ББ-102"]
    assert expand("СС-999/1-2", known) == []
    assert expand("1 КУРС на базе", known) == []


def test_состояния_дней_и_чужие_знаки():
    known = {"АА-101/1", "АА-101/2", "ББ-102"}
    got = parse(SHEET, known, TODAY)
    # Неделя целиком: сессия со 7 по 13 сентября у обеих групп диапазона.
    assert got["АА-101/1"]["2026-09-07"] == SESSION
    assert got["АА-101/2"]["2026-09-13"] == SESSION
    # Каникулы — с 28 сентября по 4 октября.
    assert got["АА-101/1"]["2026-09-28"] == HOLIDAYS
    assert got["АА-101/1"]["2026-10-04"] == HOLIDAYS
    # Практика по дням недели.
    assert got["ББ-102"]["2026-09-01"] == PRACTICE
    assert got["ББ-102"]["2026-09-22"] == PRACTICE
    # «Дфз» — зачёт на обычном занятии, день не помечен; пустая группа — пусто.
    assert "2026-10-05" not in got["ББ-102"]
    assert "ВВ-103" not in got


def test_чужой_знак_и_сдвинутая_строка_расписание_не_валят():
    # Поломки листа графика: незнакомый знак и сдвиг строки на столбец.
    # График вправе промолчать, но не упасть: расписание от него не зависит.
    corrupted = _sheet([
        ["месяц", "сентябрь", "", "", ""],
        ["№ недели", "1", "2", "3", "4"],
        ["дата", "1-6", "7-13", "14-20", "21-27"],
        ["1 КУРС"],
        ["АА-101/1-2", "", "??", "", ""],
        ["ББ-102", "", "", "::", "="],  # сдвиг: неделя 3 вместо 2
    ])
    got = parse(corrupted, {"АА-101/1", "ББ-102"}, TODAY)
    assert "АА-101/1" not in got  # чужой знак — день не помечен
    assert got["ББ-102"]["2026-09-14"] == SESSION
    assert got["ББ-102"]["2026-09-21"] == HOLIDAYS


def test_пустая_неделя_ничего_не_помечает():
    empty = _sheet([
        ["месяц", "сентябрь", "", ""],
        ["№ недели", "1", "2", "3"],
        ["дата", "1-6", "7-13", "14-20"],
        ["1 КУРС"],
        ["АА-101/1", "", "", ""],
    ])
    assert parse(empty, {"АА-101/1"}, TODAY) == {}


def test_без_заголовка_недель_график_пуст():
    assert parse("", {"АА-101/1"}, TODAY) == {}
    assert parse(_sheet([["АА-101/1", "::"]]), {"АА-101/1"}, TODAY) == {}
