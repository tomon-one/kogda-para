def key(name: str) -> str:
    """Ключ сверки: строчные, ё → е, лишние пробелы прочь."""
    text = name.strip().lower().replace("ё", "е")
    return re.sub(r"\s+", " ", text)


def split_suffix(name: str) -> tuple[str, str]:
    """«Информатика (Пр)» → («Информатика», «(Пр)»); «История ЗАЧЕТ» → («История», "")."""
    base = MARK.sub("", name)
    match = SUFFIX.search(base)
    if match is None:
        return base.strip(), ""
    suffix = match.group(0).strip()
    if not suffix.endswith(")"):
        suffix = ""
    return base[: match.start()].rstrip(), suffix


