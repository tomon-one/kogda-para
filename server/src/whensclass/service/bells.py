"""Расписание звонков.

Обычная сетка — здесь, а не в приложении: поправить время на сервере — правка
и выкладка службы, а обновление APK у всех одногруппников — история на неделю.
Она с официальной картинки колледжа от 7 сентября 2026 года. После правки
службу перезапускает выкладка: заходы «за 8 минут до пары» планируются при
запуске — по обычной сетке и в день со своими звонками.

День со своими звонками (сокращённые пары перед праздником) колледж пишет в
листе: время под номером каждой пары. Разбор кладёт его в снимок, а отсюда
берётся, чем день отличается от обычного.
"""

from __future__ import annotations

from datetime import date

from ..domain.models import Snapshot

# Номер пары -> ["начало", "конец"] в местном времени, 24 часа.
BELLS: dict[str, list[str]] = {
    "1": ["09:00", "10:30"],
    "2": ["10:40", "12:10"],
    "3": ["12:30", "14:00"],
    "4": ["14:20", "15:50"],
    "5": ["16:00", "17:30"],
    "6": ["17:40", "19:10"],
}


def own_bells(
    snapshot: Snapshot, day: date, usual: dict[str, list[str]] | None = None
) -> dict[str, list[str]] | None:
    """Звонки дня, если в листе они не такие, как в обычной сетке; иначе None.

    Сетка дня целая — время каждой пары, что стоит в листе в этот день: она
    заменяет обычную, а не дополняет её.
    """
    usual = BELLS if usual is None else usual
    grid = snapshot.bells.get(day)
    if not grid or all(usual.get(number) == span for number, span in grid.items()):
        return None
    return grid
